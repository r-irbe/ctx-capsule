export function renderActiveFleetToml(
  instances: readonly LlamaInstanceSpec[],
  activeInstanceId: string,
  slabPolicy: string,
): string {
  const lines: string[] = [
    "# =============================================================================",
    "# Layer 4: instances/active_fleet.toml -- Multi-Model llama.cpp Fleet & Slabs",
    "# =============================================================================",
    "",
    "[fleet]",
    `active_instance_id = "${escapeTomlString(activeInstanceId)}"`,
    `slab_arbitration_policy = "${escapeTomlString(slabPolicy)}"`,
    `total_instances = ${instances.length}`,
    "",
  ];

  for (const inst of instances) {
    lines.push(`[fleet.instances."${escapeTomlString(inst.id)}"]`);
    lines.push(`label = "${escapeTomlString(inst.label)}"`);
    lines.push(`engine_flavor = "${escapeTomlString(inst.engineFlavor)}"`);
    lines.push(`binary_path = "${escapeTomlString(inst.binaryPath)}"`);
    lines.push(`model_id = "${escapeTomlString(inst.modelId)}"`);
    lines.push(`template_id = "${escapeTomlString(inst.templateId)}"`);
    lines.push(`host = "${escapeTomlString(inst.host)}"`);
    lines.push(`port = ${inst.port}`);
    lines.push(`numa_nodes = "${escapeTomlString(inst.numaNodes)}"`);
    lines.push(`gpu_device = ${inst.gpuDevice}`);
    lines.push(`vram_budget_gib = ${inst.vramBudgetGiB.toFixed(2)}`);
    lines.push(`slab_priority = "${escapeTomlString(inst.slabPriority)}"`);
    lines.push(`status = "${escapeTomlString(inst.status)}"`);
    lines.push(`pid = ${inst.pid ?? 0}`);
    lines.push(`active_slots = ${inst.activeSlots}`);
    lines.push(
      `last_replaced_from_binary = "${escapeTomlString(inst.lastReplacedFromBinary ?? "none")}"`,
    );
    lines.push("");
  }

  return lines.join("\n");
}

