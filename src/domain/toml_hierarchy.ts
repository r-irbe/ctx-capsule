/**
 * Pure Functional Hierarchical TOML Compiler, Parser, and Merger.
 *
 * Implements the 5-layer declarative TOML configuration lattice:
 *   Layer 0: `00-defaults.toml`            (Base engine & capsule defaults)
 *   Layer 1: `hardware/<profile>.toml`     (NUMA, CPU threads, GPU L2, io_uring, HugeTLB)
 *   Layer 2: `models/<model>.toml`         (Checkpoint paths, architecture, MLA, MoE -ot)
 *   Layer 3: `templates/<template>.toml`   (Reusable presets: coding_pinpoint, low_vram_1m, etc.)
 *   Layer 4: `instances/active_fleet.toml` (Multi-model llama-server pool & slab arbitration)
 *   Compiled Output: `models.toml`         (Unified launcher-compatible declarative TOML)
 *
 * Zero I/O imports. Returns `Result<T, DomainError>` for all parsing and compilation steps.
 */

import { DomainErrors, type DomainError, Result } from "./result.ts";
import {
  type CapsuleControlState,
  type ConfigTemplateSpec,
  type HardwareProfileSpec,
  type LlamaInstanceSpec,
  type ModelSpec,
  SETTINGS_SCHEMA,
} from "./types.ts";

export interface HierarchicalTomlBundle {
  readonly defaultsToml: string;
  readonly hardwareByProfile: Readonly<Record<string, string>>;
  readonly modelsById: Readonly<Record<string, string>>;
  readonly templatesById: Readonly<Record<string, string>>;
  readonly activeFleetToml: string;
  readonly compiledModelsToml: string;
  readonly resolvedActiveSettings: Readonly<Record<string, string>>;
}

function escapeTomlString(raw: string): string {
  return raw.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function formatTomlValue(val: string | number | boolean | readonly string[]): string {
  if (typeof val === "boolean") {
    return val ? "true" : "false";
  }
  if (typeof val === "number") {
    return Number.isInteger(val) ? String(val) : val.toFixed(2);
  }
  if (Array.isArray(val)) {
    const items = (val as readonly string[]).map((item) => `"${escapeTomlString(item)}"`).join(", ");
    return `[${items}]`;
  }
  const str = String(val);
  if (/^-?\d+$/.test(str) || /^-?\d+\.\d+$/.test(str)) {
    return str;
  }
  if (str === "true" || str === "false") {
    return str;
  }
  return `"${escapeTomlString(str)}"`;
}

/**
 * Pure deterministic layer merge:
 * `defaults -> hardware -> model.recommendedSettings -> template.overrides -> userSettings`
 */
export function resolveHierarchicalSettings(state: CapsuleControlState): Readonly<Record<string, string>> {
  const merged: Record<string, string> = {};

  // Layer 0: Schema defaults
  for (const item of SETTINGS_SCHEMA) {
    merged[item.key] = item.defaultValue;
  }

  // Layer 1: Active Hardware Profile defaults
  const hw = state.hardwareProfiles.find((p) => p.id === state.activeHardwareProfileId);
  if (hw) {
    for (const [k, v] of Object.entries(hw.defaults)) {
      merged[k] = v;
    }
  }

  // Layer 2: Active Model recommended settings
  const model = state.models.find((m) => m.id === state.activeModelId);
  if (model) {
    for (const [k, v] of Object.entries(model.recommendedSettings)) {
      merged[k] = v;
    }
  }

  // Layer 3: Active Template overrides
  const template = state.templates.find((t) => t.id === state.activeTemplateId);
  if (template) {
    for (const [k, v] of Object.entries(template.overrides)) {
      merged[k] = v;
    }
  }

  // Layer 4: Explicit user overrides in current state
  for (const [k, v] of Object.entries(state.settingsValues)) {
    merged[k] = v;
  }

  merged.active_model = state.activeModelId;
  merged.active_template = state.activeTemplateId;
  merged.hardware_profile = state.activeHardwareProfileId;
  merged.active_instance = state.activeInstanceId;

  return Object.freeze(merged);
}

export function renderDefaultsToml(): string {
  const lines: string[] = [
    "# =============================================================================",
    "# Layer 0: 00-defaults.toml -- Base Engine, Evidence & Context Capsule Defaults",
    "# Generated by ctx-capsule TypeScript Hexagonal Config Builder",
    "# =============================================================================",
    "",
    "[meta]",
    'layer = "00-defaults"',
    "schema_version = 2",
    "",
    "[defaults]",
  ];

  for (const opt of SETTINGS_SCHEMA) {
    lines.push(`${opt.key} = "${escapeTomlString(opt.defaultValue)}" # ${opt.cliFlag}`);
  }
  lines.push("");
  lines.push("[pto]");
  lines.push(`pto_mode = "irpgo_thinlto_split"`);
  lines.push(`pto_trace_workload = "full_6stage_server_sweep"`);
  lines.push(`pto_toolchain = "clang21_lld_znver3"`);
  lines.push(`pto_target_linkage = "static_plus_shared_libs"`);
  lines.push(`profile_dir = ".pi/pto-profiles"`);
  lines.push(`merged_profdata = ".pi/pto-profiles/merged.profdata"`);
  lines.push(`optimized_binary = "build-pto/bin/llama-server"`);
  lines.push("");
  return lines.join("\n");
}

export function renderHardwareProfileToml(hw: HardwareProfileSpec): string {
  const lines: string[] = [
    `# =============================================================================`,
    `# Layer 1: hardware/${hw.id}.toml -- Hardware Topology Profile`,
    `# =============================================================================`,
    "",
    "[hardware]",
    `id = "${escapeTomlString(hw.id)}"`,
    `display_name = "${escapeTomlString(hw.displayName)}"`,
    `cpu_topology = "${escapeTomlString(hw.cpuTopology)}"`,
    `gpu_topology = "${escapeTomlString(hw.gpuTopology)}"`,
    `storage_topology = "${escapeTomlString(hw.storageTopology)}"`,
    "",
    "[hardware.defaults]",
  ];

  for (const [k, v] of Object.entries(hw.defaults)) {
    lines.push(`${k} = "${escapeTomlString(v)}"`);
  }
  lines.push("");
  lines.push("[pto]");
  lines.push(`pto_mode = "irpgo_thinlto_split"`);
  lines.push(`pto_toolchain = "clang21_lld_znver3"`);
  lines.push(`pto_target_linkage = "static_plus_shared_libs"`);
  lines.push(`cflags = "-O3 -march=znver3 -mtune=znver3 -fsplit-machine-functions -flto=thin"`);
  lines.push(`ldflags = "-fuse-ld=lld -Wl,--icf=safe -Wl,--thinlto-cache-dir=.pi/thinlto-cache"`);
  lines.push("");
  return lines.join("\n");
}

export function renderModelToml(model: ModelSpec): string {
  const lines: string[] = [
    `# =============================================================================`,
    `# Layer 2: models/${model.id}.toml -- Declarative Model Specification`,
    `# =============================================================================`,
    "",
    `[models.${model.id}]`,
    `display_name = "${escapeTomlString(model.displayName)}"`,
    `architecture = "${escapeTomlString(model.architecture)}"`,
    `parameter_scale = "${escapeTomlString(model.parameterScale)}"`,
    `quantization = "${escapeTomlString(model.quantization)}"`,
    `disk_size_gib = ${model.diskSizeGiB.toFixed(2)}`,
    `vram_footprint_gib = ${model.vramFootprintGiB.toFixed(2)}`,
    `ram_footprint_gib = ${model.ramFootprintGiB.toFixed(2)}`,
    `path = "${escapeTomlString(model.primaryPath)}"`,
    `fallback_paths = ${formatTomlValue(model.fallbackPaths)}`,
    `default_template = "${escapeTomlString(model.defaultTemplateId)}"`,
    `notes = "${escapeTomlString(model.notes)}"`,
    "",
    `[models.${model.id}.recommended]`,
  ];

  for (const [k, v] of Object.entries(model.recommendedSettings)) {
    lines.push(`${k} = "${escapeTomlString(v)}"`);
  }
  lines.push("");
  return lines.join("\n");
}

